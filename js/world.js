// 盤面の座標。横と縦は同じ単位で、核は (0.5, 0.5)。
// 画面の形は座標に入れない。入れると、同じパッチが画面の縦横比で違う音になる
// （縦に置いた星だけ、スマホとウルトラワイドで 14dB ずれていた）。
// 画面が決めるのは「どこまで見えるか」だけ。

// どの画面でも必ず見せる縦の幅。スマホの盤面（横 1 に対して縦がおよそ 1.25）に合わせた。
// 横は 0〜1、縦は 0.5 ± 0.625 が必ず収まる。広い画面では、その外に宇宙が続く。
export const Y_SPAN = 1.25;

// 止まっている星を置ける範囲。広い画面の端まで置けるように、見える範囲より広く取る。
export const POS_MIN = -1.5;
export const POS_MAX = 2.5;

export function clampPos(v) {
  return Math.min(POS_MAX, Math.max(POS_MIN, v));
}
